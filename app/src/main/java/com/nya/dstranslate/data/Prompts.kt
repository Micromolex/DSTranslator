package com.nya.dstranslate.data

/** Направление перевода. */
enum class Lang(val tag: String, val label: String, val flag: String, val speech: String) {
    RU("ru", "Русский", "🇷🇺", "ru-RU"),
    ZH("zh", "中文 (普通话)", "🇨🇳", "zh-CN");

    fun other(): Lang = if (this == RU) ZH else RU
}

object Prompts {

    /**
     * Маркер, которым модель сообщает: на входе не осмысленная фраза на исходном
     * языке, а бессмыслица или транслитерация другого языка.
     */
    const val SKIP_SENTINEL = "[[SKIP]]"

    /** Маркер: текст — транслитерация, но смысл понятен, дальше идёт перевод. */
    const val KEEP_SENTINEL = "[[!]]"

    /**
     * Хвост промпта для авторежима.
     *
     * Распознаватель, настроенный на русский, слышит китайскую речь и записывает
     * её русскими буквами («Нихао», «мехама»). По письменности такую подделку
     * от настоящего русского не отличить — а модель отличает и говорит об этом.
     */
    private fun garbageRule(from: Lang) = """
        ВАЖНО. Иногда входной текст — не осмысленная фраза на ${from.label} языке,
        а транслитерация другого языка (например, китайская речь, записанная
        русскими буквами: «Нихао», «мэхама», «сесе»). Действуй так:
        • если смысл всё-таки понятен — начни ответ ровно с $KEEP_SENTINEL
          и сразу за ним дай обычный перевод;
        • если смысл непонятен — ответь ровно $SKIP_SENTINEL и больше ничего.
        Не извиняйся, не объясняй, что тебе что-то непонятно.
    """.trimIndent()

    /** Системный промпт: жёстко ограничивает модель только переводом. */
    fun system(from: Lang, to: Lang, strict: Boolean = false): String {
        val base = when {
            from == Lang.RU && to == Lang.ZH -> """
                Ты — профессиональный синхронный переводчик русского и китайского языков.
                Переводи текст с русского на китайский язык ПУТУНХУА (普通话, 简体字, нормативное произношение).
                Правила:
                1. Отвечай ТОЛЬКО переводом. Без пояснений, без пиньиня, без кавычек, без предисловий.
                2. Используй естественный разговорный китайский, вежливые формы там, где они уместны.
                3. Собственные имена передавай иероглифами, при необходимости транслитерацией.
                4. НИКОГДА не копируй вход в ответ и не отвечай по-русски: ответ — только
                   китайский перевод. Если вход уже на китайском — верни нормативный
                   путунхуа (简体字), но не копируй его без перевода.
                5. Если во фразе есть числа, единицы измерения или адреса — передавай их точно.
                6. Если во входе несколько предложений — переведи ВСЕ, по порядку,
                   сохраняя границы предложений. Не начинай заново, не сокращай.
            """.trimIndent()

            from == Lang.ZH && to == Lang.RU -> """
                Ты — профессиональный синхронный переводчик китайского и русского языков.
                Переводи текст с китайского (путунхуа) на русский язык.
                Правила:
                1. Отвечай ТОЛЬКО переводом. Без пояснений, без транскрипции, без кавычек, без предисловий.
                2. Используй естественный разговорный русский, сохраняй вежливость и тон оригинала.
                3. Собственные имена передавай в общепринятой русской транслитерации.
                4. НИКОГДА не копируй вход в ответ и не отвечай иероглифами: ответ — только
                   русский перевод. Если вход уже на русском — верни русский текст целиком,
                   но ни одного иероглифа в ответе быть не должно.
                5. Если фраза обрывочная (это живая речь), переводи наиболее вероятный смысл кратко.
                6. Если во входе несколько предложений — переведи ВСЕ, по порядку,
                   сохраняя границы предложений. Не начинай заново, не сокращай.
            """.trimIndent()

            else -> "Переведи текст на ${to.label}. Отвечай только переводом, без пояснений."
        }
        return if (strict) "$base\n\n${garbageRule(from)}" else base
    }

    /**
     * Обратный перевод для самопроверки в режиме «Текст».
     *
     * Основной перевод шёл `from → to`; здесь на вход приходит готовый
     * результат на языке `to`, и мы просим вернуть его на `from`. Это
     * отдельный запрос без истории диалога: он не должен менять контекст
     * основного перевода.
     */
    fun backTranslation(from: Lang, to: Lang): String = """
        Ты — проверяющий переводчик. На вход подаётся текст на ${from.label} языке.
        Переведи его обратно на ${to.label} язык как можно точнее, сохраняя смысл,
        порядок предложений и имена. Это проверка обратным переводом, а не новый ответ.
        Правила:
        1. Отвечай ТОЛЬКО переводом: без пояснений, оценок, кавычек и предисловий.
        2. Не сокращай и не пересказывай — переводи всё, что есть во входе.
        3. Если вход уже на ${to.label} языке, верни его без изменений.
    """.trimIndent()
}

/** Определение языка реплики по письменности — для автодиалога по ролям. */
object LangDetect {

    private fun isHan(code: Int) =
        code in 0x4E00..0x9FFF || code in 0x3400..0x4DBF || code in 0xF900..0xFAFF

    fun detect(text: String): Lang? {
        var han = 0
        var cyr = 0
        for (c in text) {
            val code = c.code
            when {
                isHan(code) -> han++
                code in 0x0400..0x04FF -> cyr++
            }
        }
        return when {
            han == 0 && cyr == 0 -> null
            han >= cyr -> Lang.ZH
            else -> Lang.RU
        }
    }

    /** Есть ли в строке хоть что-то осмысленное: «.» и «…» — мусор. */
    fun hasLetters(text: String): Boolean = text.count { it.isLetter() } >= 2

    /** Сколько иероглифов (ханьских знаков) в строке. */
    fun hanCount(text: String): Int = text.count { isHan(it.code) }

    /** Сколько кириллических букв в строке. */
    fun cyrCount(text: String): Int = text.count { it.code in 0x0400..0x04FF }

    /**
     * Пара языков для перевода: направление задаёт письменность текста,
     * а [fallback] используется только если в тексте нет ни иероглифов,
     * ни кириллицы (цифры, латиница, эмодзи).
     *
     * Единая точка для всех режимов: «Авто», «Текст», «Два экрана», пузырь,
     * `PROCESS_TEXT`. Раньше каждый путь решал это сам, и китайская фраза
     * могла уйти с промптом RU→ZH — модель возвращала тот же китайский текст,
     * а в поле перевода появлялся оригинал.
     */
    fun translatePair(text: String, fallback: Lang): Pair<Lang, Lang> {
        val from = detect(text) ?: fallback
        return from to from.other()
    }

    /**
     * Действительно ли текст на языке [lang].
     * Нужно, чтобы отбросить распознавание «не тем» языком:
     * на русскую речь китайская модель отвечает иероглифами и наоборот.
     */
    fun matches(text: String, lang: Lang): Boolean {
        var han = 0
        var cyr = 0
        var letters = 0
        for (c in text) {
            val code = c.code
            if (isHan(code)) {
                han++
                letters++
            } else if (code in 0x0400..0x04FF) {
                cyr++
                letters++
            } else if (c.isLetter()) {
                letters++
            }
        }
        if (letters < 2) return false
        return when (lang) {
            Lang.RU -> cyr >= 2 && han == 0
            Lang.ZH -> han >= 1 && cyr == 0
        }
    }
}

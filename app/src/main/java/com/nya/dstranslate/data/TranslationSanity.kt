package com.nya.dstranslate.data

/**
 * Проверка «модель вернула не перевод».
 *
 * Зачем: при сбое или при неверном направлении DeepSeek возвращает входной
 * текст как есть. Интерфейс показывал такую строку в поле перевода — со
 * стороны это выглядело как «перевод дублирует оригинал». После регрессии
 * в ZH→RU китайский текст мог оказаться в русском поле даже не дословно:
 * модель пересказывала вход по-китайски.
 *
 * Поэтому проверяем не только совпадение строк, но и **письменность**:
 * если ответ остался в письменности исходного языка и не соответствует
 * целевому — перевода не было.
 */
object TranslationSanity {

    /**
     * [output] — не перевод: он в письменности [from] и не в письменности
     * [to]. Для ZH→RU это любой китайский текст без кириллицы (в том числе
     * дословная копия); для RU→ZH — русский текст без иероглифов.
     */
    fun isUntranslated(source: String, output: String, from: Lang, to: Lang): Boolean {
        if (source.isBlank() || output.isBlank()) return false
        // Письменность ответа совпала с исходным языком и НЕ совпала с
        // целевым — модель не перевела (или вернула дословную копию).
        // Смешанный ответ («北京 (Пекин)») не считаем ошибкой: там есть
        // и целевая письменность.
        return LangDetect.matches(output, from) && !LangDetect.matches(output, to)
    }

    /**
     * Текст ошибки с явным направлением: «Ошибка перевода ZH->RU».
     *
     * Направление в сообщении важно: при жалобе «перевода нет» сразу видно,
     * какая именно пара языков сломалась, и не приходится угадывать по логу.
     */
    fun errorMessage(from: Lang, to: Lang, detail: String? = null): String {
        val base = "Ошибка перевода ${from.tag.uppercase()}->${to.tag.uppercase()}"
        // Причина от DeepSeekClient уже начинается с «Ошибка перевода…» —
        // срезаем повтор, чтобы в карточке не было двух одинаковых префиксов.
        val clean = detail
            ?.trim()
            ?.removePrefix("Ошибка перевода:")
            ?.removePrefix("Ошибка перевода")
            ?.trim()
            ?.takeUnless { it.isEmpty() }
        return if (clean == null) base else "$base: $clean"
    }
}

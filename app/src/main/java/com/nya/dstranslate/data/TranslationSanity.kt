package com.nya.dstranslate.data

/**
 * Проверка «модель вернула оригинал вместо перевода».
 *
 * Зачем: при сбое DeepSeek модель иногда отвечает тем же текстом, что получила
 * (или прокси подставляет исходную реплику). Интерфейс показывал такую строку
 * в поле перевода — со стороны это выглядело как «перевод дублирует оригинал».
 *
 * Не всякое совпадение — ошибка: имена, артикулы и цитаты могут переводиться
 * сами собой. Поэтому считаем эхом только случай, когда текст остался в
 * письменности ИСХОДНОГО языка и при этом не соответствует целевому:
 * русский текст в ответе на перевод RU→ZH и иероглифы в ответе ZH→RU.
 */
object TranslationSanity {

    /** [output] — тот же текст, что [source], и он не на языке перевода. */
    fun isEcho(source: String, output: String, from: Lang, to: Lang): Boolean {
        if (source.isBlank() || output.isBlank()) return false
        // Сравниваем без хвостовых пробелов и двойных переносов: модель
        // может вернуть исходник с косметическими отличиями.
        if (normalize(source) != normalize(output)) return false
        // Письменность совпала с исходным языком и НЕ совпала с целевым —
        // значит перевода не было (просто вернули вход).
        return LangDetect.matches(output, from) && !LangDetect.matches(output, to)
    }

    private fun normalize(text: String): String =
        text.replace(Regex("\\s+"), " ").trim()
}
